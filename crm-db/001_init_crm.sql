CREATE TABLE patients (
    patient_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name   VARCHAR2(80) NOT NULL,
    last_name    VARCHAR2(80) NOT NULL,
    birth_date   DATE,
    region       VARCHAR2(80),
    created_at   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE prostheses (
    prosthesis_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id     NUMBER NOT NULL,
    model          VARCHAR2(100) NOT NULL,
    serial_number  VARCHAR2(80) NOT NULL UNIQUE,
    installed_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    status         VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT fk_prostheses_patient
        FOREIGN KEY (patient_id) REFERENCES patients(patient_id),
    CONSTRAINT chk_prostheses_status
        CHECK (status IN ('ACTIVE', 'RETIRED', 'SERVICE'))
);

